const DICTS: Record<Lang, Dict> = { ru, en, tr, es, pt, de, fr, it, pl, uk, zh, ja, ko, ar, hi, id, vi };

/** язык устройства, если он есть в списке; иначе английский */
export function deviceLang(): Lang {
  for (const l of navigator.languages ?? [navigator.language]) {
    const k = (l || "").slice(0, 2).toLowerCase();
    if (k in DICTS) return k as Lang;
  }
  return "en";
}

let cur: Lang = "en";
export function setLang(l: Lang) { cur = l in DICTS ? l : "en"; document.documentElement.lang = cur; }
export function getLang() { return cur; }
/** перевод по ключу; {x} заменяются значениями из p */
export function t(key: Key, p?: Record<string, string | number>): string {
  let s = DICTS[cur][key] ?? en[key] ?? key;
  if (p) for (const [k, v] of Object.entries(p)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
